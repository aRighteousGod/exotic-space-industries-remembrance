def require(condition, message):
    if not condition:
        raise ValueError(message)


def fs(path):
    value = os.path.abspath(path)
    if os.name == "nt" and not value.startswith("\\\\?\\"):
        value = "\\\\?\\UNC\\" + value[2:] if value.startswith("\\\\") else "\\\\?\\" + value
    return Path(value)


def sha(path):
    digest = hashlib.sha256()
    with fs(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def canonical_sha(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                    allow_nan=False).encode("utf-8")).hexdigest()


def read(path):
    return json.loads(fs(path).read_text(encoding="utf-8-sig"))


def bound(base, record, label):
    require(isinstance(record, dict) and isinstance(record.get("path"), str)
            and re.fullmatch(r"[0-9a-f]{64}", record.get("sha256", "")),
            label + ": an explicit file/SHA256 reference is required")
    path = Path(record["path"])
    path = (path if path.is_absolute() else base / path).resolve()
    require(sha(path) == record["sha256"], label + ": file changed: " + str(path))
    return path


def module(path, name):
    # Trusted, explicitly selected local validator code, recorded in the receipt.
    sys.path.insert(0, str(path.parent))
    try:
        spec = importlib.util.spec_from_file_location(name, path)
        result = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(result)
        return result
    finally:
        sys.path.pop(0)


def safe_output(repo, output):
    output = output.resolve()
    staging = (repo / "output").resolve()
    require(output.is_relative_to(staging) and output != staging,
            "Output must be a new dedicated directory beneath repository output")
    require(not output.exists(), "Refusing to overwrite any existing output or historical evidence")
    return output


def validate_map(creation):
    require(isinstance(creation, list) and len(creation) == 256, "A full 256-entry calibrated lookup is required")
    for index, row in enumerate(creation):
        require(isinstance(row, list) and len(row) == 2 and type(row[0]) in (int, float) and row[0] == index / 256
                and isinstance(row[1], list) and len(row[1]) == 2
                and all(type(v) in (int, float) and math.isfinite(v) for v in row[1]),
                f"Malformed or reordered muzzle lookup entry {index}")


def shipping_value(value, artifacts, fixture_mod):
    aliases = {f"__{fixture_mod}__/candidate/{row['fixture_path']}":
               f"__{row['pack']}__/{row['path']}" for row in artifacts}
    def visit(item):
        if isinstance(item, dict):
            return {key: visit(child) for key, child in item.items()}
        if isinstance(item, list):
            return [visit(child) for child in item]
        return aliases.get(item, item) if isinstance(item, str) else item
    return visit(value)


def asset_inventory(artifacts):
    result = {}
    for row in artifacts:
        path = PurePosixPath(row["path"])
        require(row.get("profile") in PACKS and row.get("pack") == PACKS[row["profile"]]
                and not path.is_absolute() and ".." not in path.parts and "\\" not in row["path"]
                and str(path).startswith("graphics/") and path.suffix == ".png",
                "Unsafe or misowned atlas destination")
        key = row["fixture_path"]
        require(key == row["profile"] + "/" + row["path"] and key not in result,
                "Duplicate or inconsistent candidate asset path")
        result[key] = {"sha256": row["sha256"], "bytes": row["bytes"], "size": row["size"]}
    require(result, "Frozen atlas is empty")
    return result


def validate_asset_manifest(manifest, inventory, candidate_sha):
    require(manifest.get("schema") == "esir.minigun.candidate-assets.v1"
            and manifest.get("candidate_data_sha256") == candidate_sha
            and manifest.get("files") == inventory,
            "Firing run did not use the exact complete frozen PNG atlas")


def launch_fields(attack):
    result = {}
    for key in ("projectile_center", "projectile_creation_distance", "apply_projection_to_projectile_creation_position"):
        if key not in attack:
            result[key] = {"present": False}
            continue
        value = attack[key]
        if key == "projectile_center":
            require(isinstance(value, list) and len(value) == 2
                    and all(type(v) in (int, float) and math.isfinite(v) for v in value), "Invalid effective projectile center")
        elif key == "projectile_creation_distance":
            require(type(value) in (int, float) and math.isfinite(value) and value >= 0,
                    "Invalid effective projectile creation distance")
        else:
            require(type(value) is bool, "Invalid effective launch projection flag")
        result[key] = {"present": True, "value": copy.deepcopy(value)}
    return result


def validate_emission(repo, acceptance, base, emitter):
    path = bound(base, acceptance["artifact_map"], "Draft artifact map")
    mapping = read(path)
    require(mapping.get("schema") == "esir.minigun.artifact-map.v1"
            and mapping.get("complete_direction_family") is True
            and mapping.get("production_promoted") is False, "Pilot/promoted artifact maps cannot be finalized")
    root = path.parent
    require(mapping.get("graphics_data_filename") in ("candidate-graphics-data.lua", "graphics-data.lua"),
            "Unexpected emitted Lua filename")
    candidate = root / mapping["graphics_data_filename"]
    require(sha(candidate) == mapping.get("graphics_data_sha256"), "Emitted candidate Lua changed")
    art = read(root / "graphics-data.json")
    require(candidate.read_text(encoding="utf-8") == DRAFT_HEADER + "return " + emitter.lua(art) + "\n",
            "Candidate Lua and JSON do not represent the exact same deterministic emitted table")
    request = read(root / "emit-input.json")
    provenance = art["provenance"]
    require(art.get("schema") == "esir.minigun.graphics.v2" and art.get("hd_major") == 1
            and provenance.get("source_sha256") == SOURCE and provenance.get("complete_direction_family") is True
            and provenance.get("direction_indices") == list(range(256))
            and provenance.get("production_promoted") is False
            and provenance.get("muzzle_native_calibrated") is False
            and set(art.get("profiles", {})) == set(PACKS), "Emission is not an unmodified full draft")
    require(request.get("provenance") == provenance, "Emission request/provenance differs")
    validate_map(art["projectile_creation_parameters"])
    compiled_path = bound(base, acceptance["compiled_metadata"], "Compiler metadata")
    require(compiled_path.name == "metadata.json" and sha(compiled_path) == mapping["compiled_metadata_sha256"]
            == provenance["compiled_metadata_sha256"], "Full compiler lineage differs")
    anchors = bound(base, acceptance["anchors"], "Muzzle anchors")
    creation, muzzle = emitter.validate_anchors(anchors, SOURCE)
    require(creation == art["projectile_creation_parameters"] and muzzle == art["muzzle_proposal"],
            "Candidate map differs from the exact tested anchor proposal")
    require(request.get("anchors_sha256") == sha(anchors), "Emission anchor lineage differs")
    color = provenance.get("color_native_evidence")
    color_path = bound(base, color, "Native color evidence")
    # A production-shaped validator rechecks the full source PNGs and native
    # aggregate. profile() is read-only; emit() is deliberately never called.
    shadow_path = None
    if provenance.get("shadow_metadata_sha256"):
        shadow_path = bound(base, acceptance["shadow_metadata"], "Residual shadow metadata")
        require(sha(shadow_path) == provenance["shadow_metadata_sha256"], "Residual shadow lineage differs")
    shadow_evidence = provenance.get("shadow_native_evidence")
    shadow_evidence_path = bound(base, shadow_evidence, "Native residual shadows") if shadow_evidence else None
    validator = emitter.Emitter(SimpleNamespace(compiled=compiled_path.parent, mode="production",
        color_evidence=color_path, shadow_candidates=shadow_path.parent if shadow_path else None,
        shadow_evidence=shadow_evidence_path, shadow_tier=mapping["shadow_tier"],
        fixture_mod=request["fixture_mod"], anchors=anchors, output=root))
    profiles = {name: validator.profile(name) for name in PACKS}
    require(validator.color_eligible is True, "Final lossless native color evidence is missing")
    artifacts = sorted(validator.artifacts.values(), key=lambda row: (row["pack"], row["path"]))
    require(all(Path(row["source"]).resolve().is_relative_to(repo) for row in artifacts),
            "Frozen atlas sources must remain in the reviewed repository workspace")
    require(artifacts == mapping["artifacts"], "Frozen artifact map differs from the revalidated full compiler atlas")
    contract = shipping_value(art, artifacts, request["fixture_mod"])
    require(mapping["frozen_profile_contract"] == contract and contract["profiles"] == profiles,
            "Shipping profile metadata differs from the tested candidate/full compiler")
    require(art["preparing_ticks"] == validator.meta["preparing_ticks"] and art["folding_ticks"] == 18
            and provenance["render_configuration_hash"] == validator.meta["configuration_hash"]
            and provenance["compiler_sha256"] == validator.signature["script_sha256"], "Pose/render lineage differs")
    inventory = asset_inventory(artifacts)
    expected_request = [{k: row[k] for k in ("source", "pack", "path", "sha256")} for row in artifacts]
    require(request.get("artifacts") == expected_request, "Emission request PNG inventory differs")
    support = mapping.get("support_artifacts", [])
    require(len(support) == 1, "Exactly one unloaded generated HD metadata artifact is required")
    row = support[0]
    require((row.get("pack"), row.get("profile"), row.get("path"), row.get("role")) ==
            (PACKS["hd"], "hd", "lib/graphics-data.lua", "graphics_library_metadata"),
            "Unexpected HD support artifact")
    example = library_metadata(contract)
    require(sha(row["source"]) == row["sha256"] and fs(row["source"]).stat().st_size == row["bytes"]
            and fs(row["source"]).read_text(encoding="utf-8") == EXAMPLE_HEADER + "return " + emitter.lua(example) + "\n",
            "Generated HD example is unbound or differs from the full shipping profile")
    return mapping, contract, candidate, anchors, inventory


def validate_matrix(acceptance, base, matrix_validator, candidate, anchors, inventory, contract):
    path = bound(base, acceptance["firing_matrix"], "Final firing matrix")
    saved = read(path)
    mechanics = bound(base, acceptance["mechanical_data"], "Candidate mechanics")
    assets = bound(base, acceptance["candidate_assets_manifest"], "Loaded candidate PNG manifest")
    validate_asset_manifest(read(assets), inventory, sha(candidate))
    pins = {"candidate-graphics-data.lua": sha(candidate), "candidate-mechanical-data.lua": sha(mechanics),
            "muzzle-anchors.json": sha(anchors), "candidate-assets-manifest.json": sha(assets)}
    require(saved.get("schema") == 2 and saved.get("source_sha256") == SOURCE
            and saved.get("all_four_firing_configurations_passed") is True
            and saved.get("expected_lineage") == pins and saved.get("failures") == []
            and saved.get("production_approved") is False, "Full current four-configuration matrix is not accepted")
    rows = saved.get("configurations", [])
    require(len(rows) == 4 and all(type(row.get("ballistic")) is bool for row in rows)
            and {(row.get("profile"), row.get("ballistic")) for row in rows} ==
            {(profile, mode) for profile in PACKS for mode in (False, True)}, "Incomplete or duplicate firing configurations")
    directories = [Path(row["directory"]) for row in rows]
    require(all(directory.is_absolute() for directory in directories), "Retained firing paths must be absolute")
    actual = matrix_validator.summarize(directories, expected_candidate_sha256=pins["candidate-graphics-data.lua"],
        expected_mechanical_sha256=pins["candidate-mechanical-data.lua"], expected_anchors_sha256=pins["muzzle-anchors.json"],
        expected_assets_manifest_sha256=pins["candidate-assets-manifest.json"])
    require(actual == saved, "Firing matrix no longer reproduces from retained captures/reviews and exact lineage")
    mechanics_contract = None
    for row, directory in zip(rows, directories):
        manifest_path = directory / "candidate-assets-manifest.json"
        require(row["bound_files"].get("candidate-assets-manifest.json") == sha(manifest_path),
                "Firing matrix does not bind its actual loaded PNG manifest")
        validate_asset_manifest(read(manifest_path), inventory, sha(candidate))
        native = read(directory / "native-report.json")
        require(native["config"].get("assets_manifest_sha256") == sha(manifest_path),
                "Native runtime did not report the staged atlas manifest pin")
        attack = native["prototype_audit"]["effective_attack"]
        require(attack.get("projectile_creation_parameters") == contract["projectile_creation_parameters"],
                "Actual native prototype uses a different muzzle map")
        observed = {"launch_fields": launch_fields(attack)}
        observed["shell_particle"] = native["prototype_audit"].get("effective_shell_particle")
        observed["circuit_connector"] = native["prototype_audit"].get("effective_circuit_connector")
        if mechanics_contract is None:
            mechanics_contract = observed
        require(observed == mechanics_contract, "Mechanical launch/presentation contract differs across native profiles/doctrines")
    return pins, mechanics_contract, path


def validate_review(base, reference, kind, required_cases, lineage):
    """Check signed-off local review evidence, not invent a visual verdict.

    The reviewer owns interpretation. Raw reports and every cited capture are
    immutable inputs; this validator checks coverage, hashes, and exact lineage.
    """
    path = bound(base, reference, kind + " acceptance")
    review = read(path)
    require(review.get("schema") == "esir.minigun." + kind + "-acceptance.v1"
            and review.get("lineage") == lineage and review.get("passed") is True
            and review.get("failures") == [] and review.get("pending_review") == []
            and isinstance(review.get("reviewer"), str) and bool(review["reviewer"].strip()),
            kind + " acceptance is incomplete, stale, or unsigned")
    raw_records = review.get("raw_reports", {})
    require(isinstance(raw_records, dict) and raw_records, kind + " raw native reports are missing")
    raw = {key: read(bound(path.parent, record, kind + " raw report " + key)) for key, record in raw_records.items()}
    for report in raw.values():
        require(report.get("lineage") == lineage and report.get("engine_version") == "2.0.77"
                and report.get("automated_checks_passed") is True and report.get("failures") == [],
                kind + " raw engine/source/atlas lineage differs")
        for name, source in report.get("source_native_reports", {}).items():
            bound(path.parent, source, kind + " original native source " + name)
    cases = review.get("cases", [])
    require(len(cases) == len(required_cases) and {row.get("id") for row in cases} == required_cases,
            kind + " required native case inventory is incomplete or duplicated")
    for row in cases:
        require(row.get("passed") is True and isinstance(row.get("notes"), str) and row["notes"].strip(),
                kind + ": unreviewed case " + str(row.get("id")))
        require(row.get("raw_report") in raw, kind + ": case has no bound native report")
        raw_cases = raw[row["raw_report"]].get("cases", [])
        matched = [case for case in raw_cases if case.get("id") == row["id"]]
        require(len(matched) == 1 and matched[0].get("automated_checks_passed") is True
                and matched[0].get("failures") == [] and matched[0].get("observations"),
                kind + ": native observations/checks missing for " + row["id"])
        captures = row.get("captures", [])
        require(captures, kind + ": image-backed review missing for " + row["id"])
        raw_captures = matched[0].get("captures", [])
        require(len(captures) == len({capture.get("path") for capture in captures}),
                kind + ": duplicate reviewed captures")
        for capture in captures:
            require(capture in raw_captures, kind + ": reviewed image not recorded by native fixture")
            bound(path.parent, capture, kind + " reviewed capture")
        if kind == "lifecycle" and row["id"].startswith("save_load/"):
            checkpoints = matched[0].get("checkpoint_saves", [])
            require(checkpoints, "Save/load case lacks an actual mid-state save artifact")
            for record in checkpoints:
                bound(path.parent, record, "Native mid-state checkpoint save")
    return path


def consumer_combat_baselines(visual_path, lineage):
    """Bind actual pre-integration mechanics from both approved native doctrines.

    Called only after validate_review. The six successful main configurations
    must supply their own native records; no SD/HD or doctrine substitution is
    permitted. Launch, state timing and artwork were excluded by the observer;
    connector placement is additionally excluded because the user owns it.
    """
    review = read(visual_path)
    approved = next(row for row in review["cases"] if row["id"] == "mechanics/unchanged")
    raw_path = bound(visual_path.parent, review["raw_reports"][approved["raw_report"]],
                     "Approved pre-final consumer observations")
    raw = read(raw_path)
    require(raw.get("schema") == "esir.minigun.consumer-aggregate.v1",
            "Combat baseline must use the approved complete main consumer aggregate")
    mechanical = next(row for row in raw["cases"] if row["id"] == "mechanics/unchanged")
    observations = mechanical["observations"]
    require(isinstance(observations, list) and observations,
            "Approved mechanics baseline must carry the complete consumer aggregate")
    required = {(scenario, doctrine) for scenario in ("absent", "disabled", "enabled")
                for doctrine in (False, True)}
    found, doctrines = {}, {}
    allowed = {"attack", "energy_source", "energy_usage", "energy_per_shot", "attacking_speed",
               "rotation_speed", "inventory_size", "collision_box", "selection_box"}
    for name, reference in raw.get("source_native_reports", {}).items():
        if name.rsplit("/", 1)[-1] != "native-report.json":
            continue
        path = bound(visual_path.parent, reference, "Pre-final consumer native source " + name)
        native = read(path)
        config, audit = native.get("config", {}), native.get("audit", {})
        require(native.get("schema") == "esir.minigun.consumer-native.v1"
                and native.get("done") is True and native.get("engine_version") == "2.0.77"
                and native.get("lineage") == lineage and config.get("lineage") == lineage
                and config.get("standalone") is False and config.get("finalized") is False
                and type(config.get("ballistic")) is bool,
                "Combat baseline requires actual pre-final main consumer evidence")
        key = (config.get("scenario"), config["ballistic"])
        require(key in required and key not in found,
                "Duplicate or unexpected pre-final consumer mechanics source")
        require(config.get("profile") == ("hd" if key[0] == "enabled" else "sd"),
                "Pre-final mechanics source profile differs from its HD scenario")
        before, after = audit.get("before"), audit.get("after")
        require(isinstance(before, dict) and before == after and any(
            row.get("ballistic") is key[1] and row.get("before") == before and row.get("after") == after
            for row in observations), "Native mechanics are not the approved unchanged observation")
        snapshot = {key: value for key, value in before.items() if key != "circuit_connector"}
        require(set(snapshot) <= allowed and (allowed - {"energy_usage"}) <= set(snapshot)
                and isinstance(snapshot["attack"], dict), "Incomplete native combat-mechanics baseline")
        doctrine = "on" if config["ballistic"] else "off"
        value = doctrines.setdefault(doctrine, {"snapshot": snapshot, "snapshot_sha256": canonical_sha(snapshot),
                                                "source_native_reports": {}})
        require(value["snapshot"] == snapshot,
                "Native combat mechanics differ between HD scenarios for doctrine " + doctrine)
        value["source_native_reports"][key[0]] = {"path": str(path), "sha256": sha(path)}
        found[key] = True
    require(set(found) == required and set(doctrines) == {"off", "on"},
            "Both doctrines require absent, disabled and enabled pre-final native mechanics reports")
    return {"schema": "esir.minigun.consumer-combat-baselines.v1",
            "source_visual_acceptance": {"path": str(visual_path), "sha256": sha(visual_path)},
            "source_observations": {"path": str(raw_path), "sha256": sha(raw_path)},
            "excluded_user_owned_field": "circuit_connector", "doctrines": doctrines}


def prepare(repo, acceptance_path, matrix_path):
    repo = repo.resolve()
    acceptance_path = acceptance_path.resolve()
    acceptance = read(acceptance_path)
    require(acceptance.get("schema") == "esir.minigun.finalization-request.v1",
            "Unsupported finalization request")
    emitter_path = repo / GENERATOR / "emit_graphics_data.py"
    matrix_path = matrix_path.resolve()
    require(matrix_path.is_relative_to(repo) and matrix_path.name == "summarize_matrix.py",
            "Matrix validator must be the explicitly reviewed local summarize_matrix.py")
    emitter = module(emitter_path, "minigun_final_emitter")
    matrix_validator = module(matrix_path, "minigun_final_matrix")
    base = acceptance_path.parent
    mapping, contract, candidate, anchors, inventory = validate_emission(repo, acceptance, base, emitter)
    pins, mechanics, matrix = validate_matrix(acceptance, base, matrix_validator, candidate, anchors, inventory, contract)
    lineage = {"source_sha256": SOURCE, "compiled_metadata_sha256": mapping["compiled_metadata_sha256"],
               "candidate_data_sha256": pins["candidate-graphics-data.lua"],
               "mechanical_data_sha256": pins["candidate-mechanical-data.lua"],
               "anchors_sha256": pins["muzzle-anchors.json"], "atlas_inventory_sha256": canonical_sha(inventory)}
    lifecycle = validate_review(base, acceptance["lifecycle"], "lifecycle", LIFECYCLE_CASES, lineage)
    visual = validate_review(base, acceptance["visual"], "visual", VISUAL_CASES, lineage)
    combat_baselines = consumer_combat_baselines(visual, lineage)
    receipt = {"schema": "esir.minigun.finalization-receipt.v1", "lineage": lineage,
               "input_artifact_map_sha256": acceptance["artifact_map"]["sha256"],
               "finalization_request_sha256": sha(acceptance_path), "firing_matrix_sha256": sha(matrix),
               "lifecycle_acceptance_sha256": sha(lifecycle), "visual_acceptance_sha256": sha(visual),
               "validators": {"emitter": sha(emitter_path), "matrix": sha(matrix_path),
                              "matrix_evidence_contract": sha(matrix_path.parent / "evidence_contract.py"),
                              "matrix_image_review": sha(matrix_path.parent / "analyze_fixture.py"),
                              "matrix_compact_controls": sha(matrix_path.parent / "compact_flash_evidence.py"),
                              "color_aggregate": sha(repo / GENERATOR / "native-color-fixture/aggregate_evidence.py"),
                              "finalizer": sha(Path(__file__))},
               "native_mechanical_contract": mechanics,
               "consumer_combat_baselines": combat_baselines,
               "ready_for_staged_integration": True, "production_promoted": False,
               "remaining_gates": ["integrated final-data and engine load with actual shipping paths",
                   "standalone HD example load and shadow policy", "complete G6 and HD ZIPs each strictly below 256000000 bytes"]}
    final = copy.deepcopy(contract)
    final["native_launch_contract"] = copy.deepcopy(mechanics["launch_fields"])
    final["muzzle_proposal"].update(native_calibrated=True, height_compensation_verified=True,
        calibration_method="exact frozen map accepted by native image-backed full matrix",
        firing_matrix_sha256=sha(matrix))
    final["provenance"].update(status="native_accepted_ready_for_staged_integration", production_promoted=False,
        native_load_tested=True, native_filtered_seams_tested=True, native_ui_readability_tested=True,
        muzzle_native_calibrated=True, finalization_evidence=copy.deepcopy(receipt))
    return emitter, mapping, final, receipt


def write_outputs(repo, output, emitter, mapping, final, receipt):
    output = safe_output(repo, output)
    # Construct/serialize everything before creating output. A rejected gate has
    # no partially accepted output and never changes original evidence.
    example = library_metadata(final)
    header = ("-- Native-calibrated full atlas; staged integration still requires final load/package gates.\n"
              "-- blueprint: .codex/esir/blueprints/minigun-turret-graphics.md#contract\n")
    lua_text = header + "return " + emitter.lua(final) + "\n"
    example_text = EXAMPLE_HEADER + "return " + emitter.lua(example) + "\n"
    payloads = {"graphics-data.lua": lua_text.encode("utf-8"),
                "graphics-data.json": (json.dumps(final, indent=2, allow_nan=False) + "\n").encode("utf-8"),
                "hd-example-graphics-data.lua": example_text.encode("utf-8")}
    result = copy.deepcopy(mapping)
    result["frozen_profile_contract"] = final
    result["graphics_data_filename"] = "graphics-data.lua"
    result["graphics_data_sha256"] = hashlib.sha256(payloads["graphics-data.lua"]).hexdigest()
    result["support_artifacts"] = [{"source": str(output / "hd-example-graphics-data.lua"),
        "pack": PACKS["hd"], "profile": "hd", "path": "lib/graphics-data.lua",
        "role": "graphics_library_metadata", "sha256": hashlib.sha256(payloads["hd-example-graphics-data.lua"]).hexdigest(),
        "bytes": len(payloads["hd-example-graphics-data.lua"])}]
    result["finalization"] = copy.deepcopy(receipt)
    payloads["artifact-map.json"] = (json.dumps(result, indent=2, allow_nan=False) + "\n").encode("utf-8")
    receipt = copy.deepcopy(receipt)
    receipt["outputs"] = {name: {"sha256": hashlib.sha256(payload).hexdigest(), "bytes": len(payload)}
                          for name, payload in payloads.items()}
    payloads["finalization-receipt.json"] = (json.dumps(receipt, indent=2, allow_nan=False) + "\n").encode("utf-8")
    output.mkdir(parents=True)
    for name, payload in payloads.items():
        (output / name).write_bytes(payload)
    return receipt


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path.cwd())
    parser.add_argument("--acceptance", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--matrix-validator", type=Path,
                        help="Reviewed schema-2 validator; defaults to the canonical firing fixture module")
    args = parser.parse_args(argv)
    safe_output(args.repo.resolve(), args.output)
    matrix = args.matrix_validator or args.repo / GENERATOR / "firing-fixture/summarize_matrix.py"
    emitter, mapping, final, receipt = prepare(args.repo, args.acceptance, matrix)
    result = write_outputs(args.repo.resolve(), args.output, emitter, mapping, final, receipt)
    print(json.dumps({"output": str(args.output.resolve()), "ready_for_staged_integration": True,
                      "production_promoted": False, "outputs": result["outputs"]}, indent=2))
    return 0


