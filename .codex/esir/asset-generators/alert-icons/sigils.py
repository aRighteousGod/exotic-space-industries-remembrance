class Sigil:
    def __init__(self): self.shapes=[]
    def poly(self,points,material='ceramic',relief=True):
        self.shapes.append(('polygon',points,material,0,relief))
    def line(self,points,width=16,material='ceramic',relief=True):
        self.shapes.append(('polyline',points,material,width,relief))
    def ellipse(self,box,material='ceramic',relief=True):
        self.shapes.append(('ellipse',box,material,0,relief))
    def band(self,x,y,outer,inner,start,end,material='ceramic'):
        angles=[start+(end-start)*i/48 for i in range(49)]
        pts=[(x+outer*cos(a*pi/180),y+outer*sin(a*pi/180)) for a in angles]
        pts += [(x+inner*cos(a*pi/180),y+inner*sin(a*pi/180)) for a in reversed(angles)]
        self.poly(pts,material)
    def inlay(self,points,material): self.poly(points,material,False)

